import test from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = (path) => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('real full-window console uses its existing hash and actual React navigation', () => {
  const ui = read('lib/redteam/client.js')
  for (const source of [ui, read('client.js')]) {
    assert.match(source, /#redteam-full/, 'fullscreen must use existing DSH route')
    assert.match(source, /RT_NAV_PATHS/, 'navigation icons must ship in runtime')
    assert.match(source, /h\(RtNavIcon, \{ tab: t\[0\] \}\)/)
    assert.match(source, /onClick: \(\) => activate\(t\[0\]\)/)
    assert.match(source, /role: 'tab'/)
    assert.match(source, /'aria-selected': st\.tab === t\[0\]/)
    assert.match(source, /full && e\.key === 'ArrowDown'/)
    assert.match(source, /full && e\.key === 'ArrowUp'/)
  }
})

test('full layout is dark and responsive without changing the host theme', () => {
  const ui = read('lib/redteam/client.js')
  assert.match(ui, /\.rt-full\{display:grid!important;grid-template-columns:224px/)
  assert.match(ui, /\.rt-full \.rt-tabs\{grid-column:1;grid-row:2;display:flex;flex-direction:column/)
  assert.match(ui, /\.rt-full \.rt-body\{grid-column:2;grid-row:2/)
  assert.match(ui, /\.rt-full\{[^}]*background:#0c1422!important/)
  assert.match(ui, /@media\(max-width:990px\)/)
  assert.match(ui, /@media\(max-width:700px\)/)
  assert.match(ui, /\.rt-dock\{container-type:inline-size\}/)
  assert.match(ui, /@container\(max-width:700px\)/)
  assert.match(ui, /@container\(max-width:420px\)/)
  assert.match(ui, /@media\(prefers-reduced-motion:reduce\)/)
})

test('privacy and asset search keep functional APIs while using real card grids and status pills', () => {
  const ui = read('lib/redteam/client.js')
  const generated = read('client.js')
  for (const source of [ui, generated]) {
    assert.match(source, /rt-pane rt-privacy-pane/)
    assert.match(source, /rt-pane rt-survey-pane/)
    assert.match(source, /\.rt-full \.rt-privacy-pane,\.rt-full \.rt-survey-pane\{display:grid/)
    assert.match(source, /rt-status-pill rt-status-' \+ key/)
    assert.match(source, /op: 'platformConfigSave', config: \{ scanPreferences: expected, privacyManagement: policy \}/)
    assert.match(source, /op: 'privacyPosture'/)
    assert.match(source, /op: 'platformConfigGet'/)
    assert.match(source, /onClick: \(\) => search\(\)/)
    assert.match(source, /op: 'localAssetSearch'/)
  }
})

test('runtime embedded client matches source generated by official build script', () => {
  const output = execFileSync(process.execPath, ['scripts/build-client.mjs', '--check'], {
    cwd: root, encoding: 'utf8',
  })
  assert.match(output, /embedded drill matches/)
})
